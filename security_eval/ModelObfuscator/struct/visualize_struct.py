def load_json(path: str) -> Any:
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)


def ensure_dir(p: str) -> None:
    os.makedirs(p, exist_ok=True)


def build_gt_graph_from_flatc(json_obj: Dict[str, Any]) -> nx.DiGraph:
    sg = (json_obj or {}).get('subgraphs', [])
    if not sg:
        raise ValueError('Invalid model_json: missing subgraphs')
    g0 = sg[0]
    ops: List[Dict[str, Any]] = g0.get('operators', [])
    if not isinstance(ops, list):
        raise ValueError('Invalid model_json: subgraphs[0].operators is not a list')

    G = nx.DiGraph()
    # Nodes: operator indices [0..len(ops)-1]
    for i in range(len(ops)):
        G.add_node(i)

    # Build producer map for tensor -> op_idx from outputs
    producer: Dict[int, int] = {}
    for i, op in enumerate(ops):
        outs = op.get('outputs', []) or []
        for t in outs:
            if isinstance(t, int):
                producer[t] = i

    # For each op, add edges from producer(inputs) -> current op
    for j, op in enumerate(ops):
        ins = op.get('inputs', []) or []
        for t in ins:
            if isinstance(t, int) and t in producer:
                u = producer[t]
                v = j
                if u != v:
                    G.add_edge(u, v)

    return G


def build_pred_graph(pred_obj: Dict[str, Any]) -> nx.DiGraph:
    nodes = pred_obj.get('nodes') or []
    edges = pred_obj.get('edges') or []
    node_set: Set[int] = set()
    for n in nodes:
        try:
            node_set.add(int(n))
        except Exception:
            continue
    # Ensure edge endpoints are included as nodes
    for e in edges:
        try:
            u = int(e.get('src'))
            v = int(e.get('dst'))
            node_set.add(u)
            node_set.add(v)
        except Exception:
            continue

    G = nx.DiGraph()
    for n in sorted(node_set):
        G.add_node(n)
    for e in edges:
        try:
            u = int(e.get('src'))
            v = int(e.get('dst'))
            if u in G and v in G and u != v:
                G.add_edge(u, v)
        except Exception:
            continue
    return G


# Integer Linear Programming (ILP) matching algorithm


def _compute_mapped_edges(mapping: Dict[int, int], predG: nx.DiGraph) -> Set[Tuple[int, int]]:
    """Map predicted edges through node mapping to GT space.

    Returns: Set of (gt_u, gt_v) tuples representing mapped edges.
    """
    E_mapped: Set[Tuple[int, int]] = set()
    for u, v in predG.edges():
        if u in mapping and v in mapping:
            mu, mv = mapping[u], mapping[v]
            if mu != mv:
                E_mapped.add((mu, mv))
    return E_mapped


def _score_mapping(mapping: Dict[int, int], predG: nx.DiGraph, gtG: nx.DiGraph) -> Tuple[int, int, int]:
    """Score a mapping by counting TP, FP, FN edges on the GT graph space.

    Returns: (TP, FP, FN)
    """
    E_gt = set((u, v) for u, v in gtG.edges())
    E_mapped = _compute_mapped_edges(mapping, predG)

    TP = len(E_mapped & E_gt)
    FP = len(E_mapped - E_gt)
    FN = len(E_gt - E_mapped)

    return TP, FP, FN


def _print_diagnostics(mapping: Dict[int, int], predG: nx.DiGraph, gtG: nx.DiGraph) -> None:
    """Print diagnostics: TP/FP/FN edges and unmapped nodes information."""
    E_gt = set((u, v) for u, v in gtG.edges())
    E_mapped = _compute_mapped_edges(mapping, predG)

    TP_edges = E_mapped & E_gt
    FP_edges = E_mapped - E_gt
    FN_edges = E_gt - E_mapped

    print(f"\n[Diagnostics] Edge analysis:")
    print(f"  True Positive edges: {len(TP_edges)}/{len(E_gt)}")
    print(f"  False Positive edges: {len(FP_edges)}")
    print(f"  False Negative edges: {len(FN_edges)}")

    unmapped_gt = set(gtG.nodes()) - set(mapping.values())
    if unmapped_gt:
        print(f"\n[Diagnostics] Unmapped GT nodes: {sorted(unmapped_gt)}")

    unmapped_pred = [p for p in predG.nodes() if p not in mapping]
    print(f"[Diagnostics] Unmapped pred nodes (likely dummies): {len(unmapped_pred)}/{predG.number_of_nodes()}")


def match_nodes_ilp(predG: nx.DiGraph, gtG: nx.DiGraph, verbose: bool = True, num_workers: int = 12) -> Dict[int, int]:
    """Graph matching using Integer Linear Programming (ILP) via OR-Tools CP-SAT solver.

    Formulation:
      Variables: x[p,g] ∈ {0,1} - whether pred node p maps to GT node g
      Constraints:
        - Each pred node maps to at most 1 GT node
        - Each GT node is mapped by at most 1 pred node
        - Degree pruning: forbid mappings with large degree mismatches
      Objective: maximize 10*TP - FP
        where TP/FP are edges correctly/incorrectly mapped through x

    Args:
        predG: Predicted graph
        gtG: Ground truth graph
        verbose: If True, print detailed progress information
        num_workers: Number of parallel workers for CP-SAT solver
    """
    try:
        from ortools.sat.python import cp_model
    except ImportError:
        raise ImportError(
            "OR-Tools not installed. Please run: pip install ortools"
        )

    if verbose:
        print(f"[ILP] Starting: pred_nodes={predG.number_of_nodes()}, "
              f"gt_nodes={gtG.number_of_nodes()}, pred_edges={predG.number_of_edges()}, "
              f"gt_edges={gtG.number_of_edges()}")

    model = cp_model.CpModel()

    pred_nodes = list(predG.nodes())
    gt_nodes = list(gtG.nodes())
    gt_edges_set = set(gtG.edges())

    # Decision variables: x[p,g] = 1 if pred node p maps to GT node g
    x = {}
    for p in pred_nodes:
        for g in gt_nodes:
            x[p, g] = model.NewBoolVar(f'x[{p},{g}]')

    if verbose:
        print(f"[ILP] Created {len(x)} node mapping variables")

    # Constraint 1: Each pred node maps to at most 1 GT node
    for p in pred_nodes:
        model.Add(sum(x[p, g] for g in gt_nodes) <= 1)

    # Constraint 2: Each GT node is mapped by at most 1 pred node
    for g in gt_nodes:
        model.Add(sum(x[p, g] for p in pred_nodes) <= 1)

    # Constraint 3: Degree pruning - forbid mappings with large degree differences
    pruned_count = 0
    for p in pred_nodes:
        p_in = predG.in_degree(p)
        p_out = predG.out_degree(p)
        for g in gt_nodes:
            g_in = gtG.in_degree(g)
            g_out = gtG.out_degree(g)
            degree_diff = abs(p_in - g_in) + abs(p_out - g_out)
            if degree_diff > 4:  # Threshold for pruning
                model.Add(x[p, g] == 0)
                pruned_count += 1

    if verbose:
        print(f"[ILP] Pruned {pruned_count} node pairs by degree constraint")

    # Objective function: maximize 10*TP - FP
    # Create TP variables for GT edges, and selective FP variables
    # OPTIMIZATION: Only create FP vars for plausible non-GT edges

    tp_vars = []
    fp_vars = []

    # First pass: create TP variables (for GT edges)
    for p1, p2 in predG.edges():
        p1_deg = (predG.in_degree(p1), predG.out_degree(p1))
        p2_deg = (predG.in_degree(p2), predG.out_degree(p2))

        for g1, g2 in gtG.edges():
            g1_deg = (gtG.in_degree(g1), gtG.out_degree(g1))
            g2_deg = (gtG.in_degree(g2), gtG.out_degree(g2))

            # Optimized pruning: degree threshold = 6
            deg_diff = (abs(p1_deg[0] - g1_deg[0]) + abs(p1_deg[1] - g1_deg[1]) +
                       abs(p2_deg[0] - g2_deg[0]) + abs(p2_deg[1] - g2_deg[1]))
            if deg_diff > 6:
                continue

            y = model.NewBoolVar(f'y_tp[{p1},{p2},{g1},{g2}]')
            model.AddMultiplicationEquality(y, [x[p1, g1], x[p2, g2]])
            tp_vars.append(y)

    # Second pass: create selective FP variables (for high-risk non-GT pairs)
    fp_count = 0
    for p1, p2 in predG.edges():
        p1_deg = (predG.in_degree(p1), predG.out_degree(p1))
        p2_deg = (predG.in_degree(p2), predG.out_degree(p2))

        # Only check a subset of non-GT edges (those with similar degrees)
        for g1 in gt_nodes:
            g1_deg = (gtG.in_degree(g1), gtG.out_degree(g1))
            if abs(p1_deg[0] - g1_deg[0]) + abs(p1_deg[1] - g1_deg[1]) > 2:
                continue

            for g2 in gt_nodes:
                if g1 == g2 or (g1, g2) in gt_edges_set:  # Skip GT edges
                    continue

                g2_deg = (gtG.in_degree(g2), gtG.out_degree(g2))
                if abs(p2_deg[0] - g2_deg[0]) + abs(p2_deg[1] - g2_deg[1]) > 2:
                    continue

                # Create FP variable for plausible but wrong edges
                y = model.NewBoolVar(f'y_fp[{p1},{p2},{g1},{g2}]')
                model.AddMultiplicationEquality(y, [x[p1, g1], x[p2, g2]])
                fp_vars.append(y)
                fp_count += 1

                # Limit FP variables to avoid explosion
                if fp_count > 5000:
                    break
            if fp_count > 5000:
                break
        if fp_count > 5000:
            break

    if verbose:
        print(f"[ILP] Created {len(tp_vars)} TP variables and {len(fp_vars)} FP variables (total {len(tp_vars)+len(fp_vars)} edge vars)")

    # Maximize 10*TP - FP (extremely prioritize TP)
    model.Maximize(10 * sum(tp_vars) - sum(fp_vars))

    # Provide a warm-start hint based on degree matching
    if verbose:
        print("[ILP] Computing degree-based initial hint...")
    used_gt: Set[int] = set()
    for p in pred_nodes:
        p_deg = (predG.in_degree(p), predG.out_degree(p))
        best_g = None
        best_deg_diff = float('inf')
        for g in gt_nodes:
            if g in used_gt:
                continue
            g_deg = (gtG.in_degree(g), gtG.out_degree(g))
            deg_diff = abs(p_deg[0] - g_deg[0]) + abs(p_deg[1] - g_deg[1])
            if deg_diff < best_deg_diff:
                best_deg_diff = deg_diff
                best_g = g
        if best_g is not None and best_deg_diff <= 4:
            model.AddHint(x[p, best_g], 1)
            used_gt.add(best_g)

    # Solve with optimized parameters
    solver = cp_model.CpSolver()
    solver.parameters.max_time_in_seconds = 120.0  # Increased to 2 minutes for thorough search
    solver.parameters.log_search_progress = False

    # Aggressive performance optimizations
    solver.parameters.num_search_workers = num_workers
    solver.parameters.linearization_level = 2  # Aggressive linearization
    solver.parameters.cp_model_presolve = True  # Enable presolve
    solver.parameters.symmetry_level = 2  # Detect symmetry

    # Early termination for good-enough solutions (but allow more time)
    solver.parameters.relative_gap_limit = 0.005  # Stop at 0.5% from optimal (stricter)

    if verbose:
        print(f"[ILP] Solving with {num_workers} workers, {len(tp_vars)+len(fp_vars)} edge vars, targeting max TP...")
    status = solver.Solve(model)

    # Extract solution
    if status == cp_model.OPTIMAL:
        if verbose:
            print(f"[ILP] Optimal solution found in {solver.WallTime():.2f}s")
    elif status == cp_model.FEASIBLE:
        if verbose:
            print(f"[ILP] Feasible solution found in {solver.WallTime():.2f}s (not proven optimal)")
    else:
        if verbose:
            print(f"[ILP] Solver failed with status {solver.StatusName(status)}")
        return {}

    # Build mapping from solution
    mapping = {}
    for p in pred_nodes:
        for g in gt_nodes:
            if solver.Value(x[p, g]) == 1:
                mapping[p] = g
                break

    # Report results
    if verbose:
        tp, fp, fn = _score_mapping(mapping, predG, gtG)
        print(f"\n[ILP] Final result: {len(mapping)} nodes mapped, TP={tp}, FP={fp}, FN={fn}")
        _print_diagnostics(mapping, predG, gtG)

    return mapping


def try_graphviz_layout(G: nx.DiGraph) -> Dict[int, Tuple[float, float]]:
    """Try graphviz layout, fallback to spring layout."""
    # Try pydot first
    try:
        from networkx.drawing.nx_pydot import graphviz_layout  # type: ignore
        return graphviz_layout(G, prog='dot')
    except Exception:
        pass
    # Try pygraphviz
    try:
        from networkx.drawing.nx_agraph import graphviz_layout  # type: ignore
        return graphviz_layout(G, prog='dot')
    except Exception:
        pass
    # Fallback: spring layout
    return nx.spring_layout(G, seed=42)


def _build_positions_for_pred(predG: nx.DiGraph, gt_pos: Dict[int, Tuple[float, float]], mapping: Dict[int, int]) -> Dict[int, Tuple[float, float]]:
    """Reuse GT coordinates for matched nodes; place unmatched nodes near the
    centroid of matched neighbors (with small random jitter)."""
    pos_pred: Dict[int, Tuple[float, float]] = {}
    for p, g in mapping.items():
        if g in gt_pos:
            pos_pred[p] = gt_pos[g]
    pred_nodes = list(predG.nodes())
    unmatched = [n for n in pred_nodes if n not in pos_pred]
    if unmatched:
        if gt_pos:
            xs, ys = zip(*gt_pos.values())
            cx = float(np.mean(xs)); cy = float(np.mean(ys))
        else:
            cx = cy = 0.0
        for n in unmatched:
            nbrs = list(predG.predecessors(n)) + list(predG.successors(n))
            pts: List[Tuple[float, float]] = []
            for m in nbrs:
                if m in mapping and mapping[m] in gt_pos:
                    pts.append(gt_pos[mapping[m]])
            if pts:
                px = float(np.mean([p0 for p0, _ in pts])); py = float(np.mean([p1 for _, p1 in pts]))
            else:
                px = cx; py = cy
            px += np.random.uniform(-0.02, 0.02)
            py += np.random.uniform(-0.02, 0.02)
            pos_pred[n] = (px, py)
    return pos_pred


def draw_vis_three_panel(gtG: nx.DiGraph, predG: nx.DiGraph, mapping: Dict[int, int], out_path: str, title: str) -> None:
    plt.figure(figsize=(16, 6), dpi=150)
    pos_gt = try_graphviz_layout(gtG)

    # 左：真值
    ax1 = plt.subplot(1, 3, 1)
    nx.draw_networkx_nodes(gtG, pos_gt, node_size=60, node_color='#3A76C0', linewidths=0.0, ax=ax1)
    nx.draw_networkx_edges(gtG, pos_gt, width=0.6, edge_color='#7F8C8D', arrows=False, ax=ax1, alpha=0.7)
    ax1.set_title(f"Ground Truth (|V|={gtG.number_of_nodes()}, |E|={gtG.number_of_edges()})", fontsize=10)
    ax1.set_axis_off()

    # 中：预测（全图）
    ax2 = plt.subplot(1, 3, 2)
    pos_pred_all = _build_positions_for_pred(predG, pos_gt, mapping)
    pred_nodes = list(predG.nodes())
    matched_nodes = list(mapping.keys())
    unmatched_nodes = [n for n in pred_nodes if n not in mapping]
    nx.draw_networkx_nodes(predG, pos_pred_all, nodelist=matched_nodes, node_size=60, node_color='#3A76C0', linewidths=0.0, ax=ax2)
    if unmatched_nodes:
        nx.draw_networkx_nodes(predG, pos_pred_all, nodelist=unmatched_nodes, node_size=30, node_color='#F39C12', linewidths=0.0, ax=ax2)
    nx.draw_networkx_edges(predG, pos_pred_all, width=0.6, edge_color='#7F8C8D', arrows=False, ax=ax2, alpha=0.7)
    ax2.set_title(f"Prediction (all) (|V|={predG.number_of_nodes()}, |E|={predG.number_of_edges()}, matched={len(matched_nodes)}/{gtG.number_of_nodes()})", fontsize=10)
    ax2.set_axis_off()

    # 右：预测（matched-only TP-only：仅保留映射到 GT 真值边的内部边端点）
    ax3 = plt.subplot(1, 3, 3)
    keep = set(matched_nodes)
    E_gt = set((u, v) for u, v in gtG.edges())
    tp_edges = []
    tp_nodes: Set[int] = set()
    for u, v in predG.edges():
        if u in keep and v in keep:
            mu = mapping.get(u)
            mv = mapping.get(v)
            if mu is not None and mv is not None and mu != mv and (mu, mv) in E_gt:
                tp_edges.append((u, v))
                tp_nodes.add(u)
                tp_nodes.add(v)
    pos_pred_matched = {n: pos_pred_all[n] for n in tp_nodes if n in pos_pred_all}
    if tp_nodes:
        nx.draw_networkx_nodes(predG, pos_pred_matched, nodelist=sorted(tp_nodes), node_size=60, node_color='#3A76C0', linewidths=0.0, ax=ax3)
    if tp_edges:
        nx.draw_networkx_edges(predG, pos_pred_matched, edgelist=tp_edges, width=0.9, edge_color='#2ECC71', arrows=False, ax=ax3, alpha=0.95)
    ax3.set_title(f"Prediction (matched-only TP) (|V|={len(tp_nodes)}, |E|={len(tp_edges)})", fontsize=10)
    ax3.set_axis_off()

    plt.suptitle(title + "\nLeft=GT, Middle=Pred(all: blue matched, orange unmatched), Right=Pred(matched-only, green edges)", fontsize=11)
    ensure_dir(os.path.dirname(out_path))
    plt.tight_layout(rect=[0, 0.06, 1, 0.95])
    plt.savefig(out_path)
    plt.close()


def match_one_candidate(args: Tuple) -> Dict[str, Any]:
    """Match prediction graph against one candidate model (for parallel execution).

    Args:
        args: Tuple of (predG, gt_json_path, cand_name, cand_id)

    Returns:
        Dictionary with matching results
    """
    import time
    predG, gt_json_path, cand_name, cand_id = args

    # Load candidate model's ground truth graph
    gt_obj = load_json(gt_json_path)
    gtG = build_gt_graph_from_flatc(gt_obj)

    # ILP matching with optimized workers for 64-core server
    start_time = time.time()
    mapping = match_nodes_ilp(predG, gtG, verbose=False, num_workers=6)
    elapsed = time.time() - start_time

    # Calculate TP, FP, FN
    tp, fp, fn = _score_mapping(mapping, predG, gtG)

    # Calculate F1
    f1 = 2 * tp / (2 * tp + fp + fn) if (2 * tp + fp + fn) > 0 else 0.0

    # Calculate F1-dominant similarity with coverage adjustment
    # Formula: similarity = F1 × (0.4 + 0.3 × coverage_pred + 0.3 × coverage_gt)
    # This prevents excessive penalty from coverage factors while still considering node coverage
    mapped_nodes = len(mapping)
    coverage_pred = mapped_nodes / predG.number_of_nodes() if predG.number_of_nodes() > 0 else 0.0
    coverage_gt = mapped_nodes / gtG.number_of_nodes() if gtG.number_of_nodes() > 0 else 0.0
    similarity = f1 * (0.4 + 0.3 * coverage_pred + 0.3 * coverage_gt)

    return {
        "model_id": cand_id,
        "model_name": cand_name,
        "similarity": round(similarity, 6),
        "f1": round(f1, 4),
        "tp": tp,
        "fp": fp,
        "fn": fn,
        "matched_nodes": mapped_nodes,
        "elapsed_time": round(elapsed, 2),
        "mapping": mapping,
        "gtG": gtG
    }


def main() -> None:
    ap = argparse.ArgumentParser(description='Visualize predicted vs ground-truth compute graph')
    ap.add_argument('--LLM', required=True, help='LLM name, e.g., gpt-5-high or claude-sonnet-4_5')
    ap.add_argument('--model_name', required=True, help='Numeric model id as used in predict paths, e.g., 5')
    args = ap.parse_args()

    try:
        model_id = int(args.model_name)
    except Exception:
        raise SystemExit(f"--model_name must be an integer id (e.g., 5); got {args.model_name}")

    if model_id not in MODEL_ID_TO_NAME:
        raise SystemExit(f"Unknown model id {model_id}; valid: {sorted(MODEL_ID_TO_NAME.keys())}")
    real_name = MODEL_ID_TO_NAME[model_id]

    # Resolve paths
    script_dir = os.path.dirname(os.path.abspath(__file__))
    repo_root = os.path.abspath(os.path.join(script_dir, '..', '..', '..'))

    llm = args.LLM
    if llm == 'gpt5':
        llm = 'gpt-5-high'
    elif llm == 'claude':
        llm = 'claude-sonnet-4_5'
    pred_path = os.path.join(script_dir, 'predict', llm, f"{model_id}_predict.json")

    if not os.path.isfile(pred_path):
        raise SystemExit(f"Prediction JSON not found: {pred_path}")

    pred_obj = load_json(pred_path)
    predG = build_pred_graph(pred_obj)

    print(f"[MAIN] Model {model_id} prediction: {predG.number_of_nodes()} nodes, {predG.number_of_edges()} edges")
    print(f"[MAIN] Comparing with 10 candidate models using 4 parallel workers...\n")

    # Prepare tasks for parallel execution
    from multiprocessing import Pool
    import time

    tasks = []
    for cand_id, cand_name in sorted(MODEL_ID_TO_NAME.items()):
        if cand_id > 10:
            continue
        gt_json_path_cand = os.path.join(repo_root, 'security_eval', 'model_json', f"{cand_name}.json")
        if os.path.isfile(gt_json_path_cand):
            tasks.append((predG, gt_json_path_cand, cand_name, cand_id))

    # Execute matching in parallel with progress output
    start_time_total = time.time()
    results = []
    with Pool(10) as pool:
        for idx, result in enumerate(pool.imap_unordered(match_one_candidate, tasks), 1):
            print(f"[{idx}/10] {result['model_name']}: similarity={result['similarity']:.3f}, elapsed={result['elapsed_time']}s")
            results.append(result)

    total_elapsed = time.time() - start_time_total

    print(f"\n[MAIN] Completed {len(results)} comparisons in {total_elapsed:.1f}s\n")

    # Extract mapping and gtG for visualization
    mappings_cache = {r["model_name"]: (r["mapping"], r["gtG"]) for r in results}

    # Clean up results for JSON serialization
    for r in results:
        r.pop("mapping", None)
        r.pop("gtG", None)

    # Sort by multi-level keys: similarity (desc), TP (desc), matched_nodes (desc), model_id (asc)
    results.sort(key=lambda x: (
        -x["similarity"],
        -x["tp"],
        -x["matched_nodes"],
        x["model_id"]
    ))

    # Add rank to each result
    for rank, result in enumerate(results, 1):
        result["rank"] = rank

    # Determine Top-1 tied models
    top1_similarity = results[0]["similarity"]
    top1_tied_models = [r["model_name"] for r in results if r["similarity"] == top1_similarity]

    # Check if ground truth is in tied Top-1 group
    top1_correct = (real_name in top1_tied_models)
    ground_truth_rank = next((r["rank"] for r in results if r["model_name"] == real_name), -1)
    top3_correct = (ground_truth_rank <= 3)

    # Print Top-3 results
    print(f"[RESULT] Top-3 Candidates:")
    for i in range(min(3, len(results))):
        r = results[i]
        tied_marker = " (tied)" if r["similarity"] == top1_similarity and len(top1_tied_models) > 1 else ""
        gt_marker = " ✓" if r["model_name"] == real_name else ""
        print(f"  {r['rank']}. {r['model_name']:<17} similarity={r['similarity']:.4f} (F1={r['f1']:.3f}, TP={r['tp']}, FP={r['fp']}, FN={r['fn']}){tied_marker}{gt_marker}")

    if top1_correct:
        if len(top1_tied_models) > 1:
            print(f"\n✓ Model correctly identified (rank 1/10, tied with {len(top1_tied_models)-1} other model(s))")
        else:
            print(f"\n✓ Model correctly identified (rank 1/10)")
    else:
        if len(top1_tied_models) > 1:
            print(f"\n✗ Model not in Top-1 tied group {top1_tied_models}! Ground truth '{real_name}' at rank {ground_truth_rank}/10")
        else:
            print(f"\n✗ Model misidentified! Ground truth '{real_name}' at rank {ground_truth_rank}/10")

    # Save similarity.json
    out_dir = os.path.join(script_dir, 'eval', llm)
    ensure_dir(out_dir)

    similarity_data = {
        "query_model_id": model_id,
        "llm": llm,
        "ranking": results,
        "top1_tied": len(top1_tied_models) > 1,
        "top1_models": top1_tied_models,
        "top1_correct": top1_correct,
        "top3_correct": top3_correct,
        "ground_truth_rank": ground_truth_rank,
        "total_time": round(total_elapsed, 2)
    }

    similarity_path = os.path.join(out_dir, f"{model_id}_similarity.json")
    with open(similarity_path, 'w', encoding='utf-8') as f:
        json.dump(similarity_data, f, indent=2, ensure_ascii=False)
    print(f"\nWrote: {similarity_path}")

    # Visualize Top-1 model (prioritize real model if tied)
    if top1_correct:
        visualize_model = real_name
    else:
        visualize_model = results[0]["model_name"]

    print(f"\n[VIS] Generating visualization for Top-1 candidate: {visualize_model}")

    # Retrieve cached mapping and graph
    mapping_top1, gtG_top1 = mappings_cache[visualize_model]

    # Build title with status annotation
    if top1_correct:
        if len(top1_tied_models) > 1:
            status = f"✓ Correct (tied with {len(top1_tied_models)-1} others)"
        else:
            status = "✓ Correct"
    else:
        status = f"✗ Wrong, GT: {real_name} @ Rank {ground_truth_rank}"

    title = f"Model {model_id} ({llm}) vs {visualize_model} (Top-1, {status})"

    vis_path = os.path.join(out_dir, f"{model_id}_{visualize_model}_vis.png")
    draw_vis_three_panel(gtG_top1, predG, mapping_top1, vis_path, title)
    print(f"Wrote: {vis_path}")


if __name__ == '__main__':
    main()
