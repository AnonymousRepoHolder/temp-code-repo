"""
Decrypt real operator types for a virtualized model (offline ground truth).

Usage (default paths: /ModelVitualizer):
  python security_eval/NeuralVirtualizer/opTypes/decrypt_truth.py --model_name 1

It will read (from the same directory as this script by default):
  v_infos/<model>_v_infos.json
  keys_and_offsets.bin

And write:
  real/<model>_real.json

Output format (default JSON array with one operator per line):
  {"idx": 123, "type": "CONV_2D"}\n

Notes:
- Uses plaintext keys format generated by scripts/generate_keys.py (168 bytes).
- Only OP domain key and OP modulus are needed.
- No decryption of params/graph/shape is required.
"""

from __future__ import annotations
import argparse
import base64
import json
import os
import struct
import sys
from typing import Any, Dict, List, Tuple

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
from cryptography.hazmat.backends import default_backend


def read_keys_and_offsets(bin_path: str) -> Tuple[int, Dict[str, Tuple[bytes, bytes]]]:
    """Read 168-byte keys_and_offsets.bin.

    Returns:
      op_modulus (int), domains dict: name -> (key32, nonce_base8)
    """
    with open(bin_path, 'rb') as f:
        data = f.read()
    if len(data) != 168:
        raise ValueError(f"Invalid keys file size {len(data)} (expected 168): {bin_path}")

    op_modulus, conn_modulus = struct.unpack('<II', data[:8])  # noqa: F841 (conn_modulus unused)
    off = 8
    domains: Dict[str, Tuple[bytes, bytes]] = {}
    order = ['op', 'param', 'graph', 'shape']
    for name in order:
        key = data[off:off+32]; off += 32
        nonce_base = data[off:off+8]; off += 8
        domains[name] = (key, nonce_base)
    return op_modulus, domains


def aes256_ctr_decrypt_short(b64_ct: str, key: bytes, nonce_base: bytes, counter_qword: int) -> bytes:
    ct = base64.b64decode(b64_ct)
    nonce = nonce_base + struct.pack('<Q', counter_qword)
    cipher = Cipher(algorithms.AES(key), modes.CTR(nonce), backend=default_backend())
    decryptor = cipher.decryptor()
    return decryptor.update(ct) + decryptor.finalize()


def load_json(path: str) -> Dict[str, Any]:
    with open(path, 'r', encoding='utf-8') as f:
        return json.load(f)


def save_json_array_one_per_line(path: str, rows: List[Dict[str, Any]]) -> None:
    """Write a JSON array where each element occupies exactly one line.

    This preserves valid JSON, and makes visual diff easy:
    [\n{...},\n{...}\n]
    """
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write('[\n')
        for i, row in enumerate(rows):
            line = json.dumps(row, ensure_ascii=False, separators=(',', ':'))
            if i < len(rows) - 1:
                f.write('    ' + line + ',\n')
            else:
                f.write('    ' + line + '\n')
        f.write(']')


def save_jsonl(path: str, rows: List[Dict[str, Any]]) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False, separators=(",", ":")) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description='Decrypt real op types for a virtualized model')
    parser.add_argument('--model_name', required=True, help='Model name, e.g., lenet')
    args = parser.parse_args()

    # Default to the directory where this script resides
    base_dir = os.path.dirname(os.path.abspath(__file__))
    v_infos_path = os.path.join(base_dir, f"v_infos/{args.model_name}_v_infos.json")
    keys_path = os.path.join(base_dir, 'keys_and_offsets.bin')
    out_path = os.path.join(base_dir, f"real/{args.model_name}_real.json")

    # Import op_type_mapping from utils
    # Add repo root (two levels up from this script) to path for utils import
    repo_root = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
    if repo_root not in sys.path:
        sys.path.append(repo_root)
    from utils.utils import op_type_mapping  # type: ignore

    # Load keys
    op_modulus, domains = read_keys_and_offsets(keys_path)
    op_key, op_nonce_base = domains['op']

    # Load v_infos
    v_infos = load_json(v_infos_path)
    operators = v_infos.get('operators', [])
    if not isinstance(operators, list):
        raise ValueError('Invalid v_infos: operators is not a list')

    results: List[Dict[str, Any]] = []
    for v_op in operators:
        try:
            op_index = int(v_op['index'])
            v_code_b64 = v_op['v_op_code_data']
        except Exception:
            # Skip malformed entries
            continue

        pt = aes256_ctr_decrypt_short(v_code_b64, op_key, op_nonce_base, op_index)
        if len(pt) < 4:
            # Unexpected; skip
            continue
        v_code, = struct.unpack('<I', pt[:4])
        real_code = v_code % op_modulus

        op_type = op_type_mapping.get(real_code, f"UNKNOWN_OP_{real_code}")
        results.append({
            'idx': op_index,
            'type': op_type,
        })

    # Keep original order as in v_infos for easy alignment with predict.json
    # Default: valid JSON array, one operator per line, keep .json extension.
    save_json_array_one_per_line(out_path, results)
    print(f"Wrote ground-truth: {out_path} (ops: {len(results)})")


if __name__ == '__main__':
    main()
