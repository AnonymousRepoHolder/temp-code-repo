"""
Compare LLM predictions (predict.json) with decrypted ground truth (real.json).

Usage:
  python security_eval/NeuralVirtualizer/opTypes/compare_eval.py --model_name 1 --LLM [gpt5/claude]

Expected files (under current dir by default):
  ./predict/<LLM>/<model>_predict.json   # LLM output (JSON array)
  ./real/<model>_real.json               # ground truth generated by decrypt_truth.py (JSON array)

Output:
  ./eval/<LLM>/<model>_<name>_eval.json               # concise metrics JSON

Reported metrics (only these 5):
  - top1_acc:   Top-1 accuracy.
  - top3_acc:   Top-3 accuracy.
  - top5_acc:   Top-5 accuracy.
  - main_dist_coverage: fraction of operators sharing the most frequent predicted probability vector
                        (vectors are over the operator type universe; rounded to 1e-3 for grouping).
  - mean_js_to_main: mean Jensen-Shannon divergence between each predicted probability vector and the
                     most frequent ("main") vector (lower means more homogeneous predictions).

Rules:
  - No CSV output, JSON only.
  - Unsupported types are mapped to OTHER bucket; UNKNOWN is kept as its own bucket.
  - Match by virtualized idx.
"""

from __future__ import annotations
import argparse
import json
import math
import os
import re
import sys
from typing import Any, Dict, List, Tuple, Set


def load_json_array(path: str) -> List[Dict[str, Any]]:
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    if not isinstance(data, list):
        raise ValueError(f"Expect a JSON array in {path}")
    return data


def save_json(path: str, obj: Any) -> None:
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(obj, f, ensure_ascii=False, indent=2)


def import_supported_types() -> Set[str]:
    try:
        repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
        if repo_root not in sys.path:
            sys.path.append(repo_root)
        from utils.utils import op_type_mapping  # type: ignore
        return {str(v).upper() for v in op_type_mapping.values()}
    except Exception:
        return set()


_ALIASES = {
    'CONV2D': 'CONV_2D',
    'DEPTHWISE_CONV2D': 'DEPTHWISE_CONV_2D',
    'RELU_6': 'RELU6',
    'BATCHMATMUL': 'BATCH_MATMUL',
}


def norm_type_name(name: str) -> str:
    if not isinstance(name, str):
        return 'UNKNOWN'
    s = name.strip().upper()
    s = re.sub(r'[^A-Z0-9]+', '_', s)
    s = re.sub(r'_+', '_', s).strip('_')
    if s in _ALIASES:
        s = _ALIASES[s]
    return s or 'UNKNOWN'


def to_int(x: Any) -> Tuple[int, bool]:
    try:
        return int(x), True
    except Exception:
        return 0, False


def _js_divergence(p: List[float], q: List[float], eps: float = 1e-12) -> float:
    """Jensen-Shannon divergence (natural log). p, q are prob vectors of same length."""
    import math as _m
    def _kl(a: List[float], b: List[float]) -> float:
        s = 0.0
        for ai, bi in zip(a, b):
            ai = max(eps, min(1.0, ai))
            bi = max(eps, min(1.0, bi))
            s += ai * _m.log(ai / bi)
        return s
    m = [(pi + qi) * 0.5 for pi, qi in zip(p, q)]
    return 0.5 * (_kl(p, m) + _kl(q, m))


def compute_metrics(model_name: str, pred_path: str, real_path: str, out_path: str) -> Dict[str, Any]:
    supported = import_supported_types()
    preds = load_json_array(pred_path)
    reals = load_json_array(real_path)

    # Build idx -> real type map
    real_by_idx: Dict[Any, str] = {}
    non_int_real_idx: List[Any] = []
    for item in reals:
        idx = item.get('idx')
        t = norm_type_name(item.get('type', 'UNKNOWN'))
        i, ok = to_int(idx)
        key = i if ok else idx
        if not ok:
            non_int_real_idx.append(idx)
        real_by_idx[key] = t

    # (Removed type-level aggregation and grouping; keep only concise metrics and per-op output)

    # Iterate predictions
    top1_hit = top3_hit = top5_hit = 0
    # For distribution analysis
    merged_list: List[Dict[str, float]] = []
    seen_types: Set[str] = set()
    matched = 0
    missing_in_pred = 0
    missing_in_real = 0
    non_int_pred_idx: List[Any] = []

    # Per-op records: build only for indices that exist in real_by_idx
    # We will fill as we see predictions; later we will add placeholders for those missing in prediction
    per_op_by_idx: Dict[Any, Dict[str, Any]] = {}

    for p in preds:
        idx = p.get('idx')
        i, ok = to_int(idx)
        key = i if ok else idx
        if not ok:
            non_int_pred_idx.append(idx)

        if key not in real_by_idx:
            # Prediction covers an idx not present in real
            missing_in_real += 1
            continue

        matched += 1
        real_type = norm_type_name(real_by_idx[key])

        topk = p.get('topk') or []
        names_order = [norm_type_name(x.get('type', 'UNKNOWN')) for x in topk if isinstance(x, dict)]
        for nm in names_order:
            seen_types.add(nm)

        # Collect probabilities if present; otherwise equal split
        probs_raw: List[float] = []
        has_all_p = True
        for x in topk:
            if not isinstance(x, dict):
                continue
            pv = x.get('p', None)
            if isinstance(pv, (int, float)):
                try:
                    probs_raw.append(float(pv))
                except Exception:
                    has_all_p = False
                    break
            else:
                has_all_p = False
                break

        if not names_order:
            # Empty Top-K: treat as OTHER=1.0 distribution.
            merged_list.append({'OTHER': 1.0})
            
            # Also per-op record with empty predictions
            per_op_by_idx[key] = {
                'idx': key,
                'real_type': real_type,
                'pred_topk': [],
                'rank_of_real': None,
                'p_real': 0.0,
            }
            continue

        k = len(names_order)
        if not has_all_p or len(probs_raw) != k:
            probs = [1.0 / k] * k
        else:
            # Clip and normalize
            probs = [min(1.0, max(0.0, float(v))) for v in probs_raw]
            s = sum(probs)
            if s > 0:
                probs = [v / s for v in probs]
            else:
                probs = [1.0 / k] * k

        # Merge duplicates; keep UNKNOWN as its own bucket; map unsupported to OTHER; add remainder to OTHER
        OTHER = 'OTHER'
        merged: Dict[str, float] = {}
        for name, pv in zip(names_order, probs):
            if name == 'UNKNOWN':
                label = 'UNKNOWN'
            elif name in supported:
                label = name
            else:
                label = OTHER
            merged[label] = merged.get(label, 0.0) + pv
        sum_topk = sum(merged.values())
        if sum_topk < 1.0:
            merged[OTHER] = merged.get(OTHER, 0.0) + (1.0 - sum_topk)
        merged_list.append(merged)

        preds_norm = names_order

        # Build per-op topk with normalized types and normalized probabilities (no merging to OTHER)
        pred_topk_norm: List[Dict[str, Any]] = [
            {'type': t, 'p': float(pv)} for t, pv in zip(names_order, probs)
        ]
        # rank of real and probability mass on real
        rank_of_real = None
        for i_pos, t in enumerate(names_order):
            if t == real_type:
                rank_of_real = i_pos + 1
                break
        p_real = sum(pv for t, pv in zip(names_order, probs) if t == real_type)
        per_op_by_idx[key] = {
            'idx': key,
            'real_type': real_type,
            'pred_topk': pred_topk_norm,
            'rank_of_real': rank_of_real,
            'p_real': float(p_real),
        }

        

        # Top-1 / Top-3 / Top-5
        if preds_norm:
            t1 = preds_norm[0]
            if t1 == real_type:
                top1_hit += 1
        if real_type in preds_norm[:3]:
            top3_hit += 1
        if real_type in preds_norm[:5]:
            top5_hit += 1

    total_real = len(real_by_idx)
    missing_in_pred = total_real - matched

    def ratio(x: float, denom: int) -> float:
        return round((x / denom) if denom else 0.0, 6)

    # Build type universe and compute main distribution & JS
    type_universe: List[str] = sorted(set(supported) | seen_types | {'UNKNOWN', 'OTHER'})
    type_index = {t: i for i, t in enumerate(type_universe)}
    vecs: List[List[float]] = []
    keys_count: Dict[Tuple[float, ...], int] = {}
    keys_for_item: List[Tuple[float, ...]] = []
    for merged in merged_list:
        v = [0.0] * len(type_universe)
        for k2, pv in merged.items():
            v[type_index[k2]] = pv
        key = tuple(round(x, 3) for x in v)
        keys_count[key] = keys_count.get(key, 0) + 1
        vecs.append(v)
        keys_for_item.append(key)
    if keys_count:
        main_key = max(keys_count.items(), key=lambda kv: kv[1])[0]
        main_vec = list(main_key)
        main_coverage = max(keys_count.values()) / len(vecs)
    else:
        main_vec = []
        main_coverage = 0.0
    mean_js = (sum(_js_divergence(v, main_vec) for v in vecs) / len(vecs)) if main_vec else 0.0

    # Concise metrics (only these 5)
    top1 = ratio(top1_hit, matched)
    top3 = ratio(top3_hit, matched)
    top5 = ratio(top5_hit, matched)

    result = {
        'model_name': model_name,
        'metrics': {
            'top1_acc': top1,
            'top3_acc': top3,
            'top5_acc': top5,
            'main_dist_coverage': round(main_coverage, 6),
            'mean_js_to_main': round(mean_js, 6),
        },
        'metrics_desc': {
            'top1_acc': 'Top-1 accuracy (fraction of operators where the first predicted type equals ground truth).',
            'top3_acc': 'Top-3 accuracy (ground truth appears within the first 3 predicted types).',
            'top5_acc': 'Top-5 accuracy (ground truth appears within the first 5 predicted types).',
            'main_dist_coverage': 'Share of operators whose predicted probability vector equals (rounded to 1e-3) the most frequent vector.',
            'mean_js_to_main': 'Mean Jensen-Shannon divergence between each predicted probability vector and the most frequent vector (lower = more homogeneous).'
        }
    }

    # Save concise metrics
    save_json(out_path, result)


    # Build and save per-op details for all real indices (ensure placeholders for missing predictions)
    # Preserve the order as in real list for stability
    per_op_records: List[Dict[str, Any]] = []
    for item in reals:
        idx_orig = item.get('idx')
        i_val, ok_val = to_int(idx_orig)
        key = i_val if ok_val else idx_orig
        rec = per_op_by_idx.get(key)
        if rec is None:
            # placeholder when prediction is missing for this real idx
            rec = {
                'idx': key,
                'real_type': norm_type_name(item.get('type', 'UNKNOWN')),
                'pred_topk': [],
                'rank_of_real': None,
                'p_real': 0.0,
            }
        per_op_records.append(rec)

    # Save to sibling per-op file (same dir as out_path)
    out_dir = os.path.dirname(out_path)
    base_name = os.path.basename(out_path)
    name_no_ext = os.path.splitext(base_name)[0]
    per_op_path = os.path.join(out_dir, f"{name_no_ext.replace('_eval', '')}_per_op.json")
    save_json(per_op_path, per_op_records)
    return result


def main() -> None:
    ap = argparse.ArgumentParser(description='Compare predict.json with real.json and output metrics JSON')
    ap.add_argument('--model_name', required=True, help='Model name, e.g., lenet')
    ap.add_argument('--LLM', required=True, help='LLM name, e.g., gpt5')
    ap.add_argument('--real_subdir', default='real', help='Ground-truth subdirectory under opTypes/, e.g., real or real_original')
    args = ap.parse_args()

    model = args.model_name
    base_dir = os.path.abspath(os.path.dirname(__file__))
    llm = args.LLM
    if llm == 'gpt5':
        llm = 'gpt-5-high'
    elif llm == 'claude':
        llm = 'claude-sonnet-4_5'
    pred_path = os.path.join(base_dir, f'predict/{llm}/{model}_predict.json')
    real_path = os.path.join(base_dir, args.real_subdir, f'{model}_real.json')
    model_map = {
        0: 'security_test',
        1: 'squeezenet',
        2: 'posenet',
        3: 'fruit',
        4: 'lenet',
        5: 'mobilenet',
        6: 'skin',
        7: 'mnasnet',
        8: 'efficientnet',
        9: 'ssd',
        10: 'depth_estimation',
    }
    name = model_map[int(model)]
    out_path = os.path.join(base_dir, f'eval/{llm}/{model}_{name}_eval.json')
    res = compute_metrics(model, pred_path, real_path, out_path)
    # Concise console summary
    m = res['metrics']
    print(
        f"Model: {model} | top1={m['top1_acc']:.3f} top3={m['top3_acc']:.3f} top5={m['top5_acc']:.3f} "
        f"main_cov={m['main_dist_coverage']:.3f} mean_js={m['mean_js_to_main']:.3f}"
    )
    print(f"Wrote: {out_path}")
    # Also inform per-op path on console for discoverability
    out_dir = os.path.dirname(out_path)
    base_name = os.path.basename(out_path)
    name_no_ext = os.path.splitext(base_name)[0]
    per_op_path = os.path.join(out_dir, f"{name_no_ext.replace('_eval', '')}_per_op.json")
    print(f"Wrote per-op: {per_op_path}")


if __name__ == '__main__':
    main()
